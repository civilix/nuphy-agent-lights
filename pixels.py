"""Clockwise loading lights on the Air75 V3 ANSI. Run to rebuild the Studio asset."""
import json
from pathlib import Path
from effort import DEFAULT_EFFORTS

FRAME_SECONDS = 0.12
# Bridge slots follow the measured ANSI lighting layout. Delete has no mapped slot.
# Start at Esc, cross the function row, then return along the bottom and left edges.
PERIMETER = (
    (0, "Escape"), *((i, f"F{i}") for i in range(1, 13)), (13, "PrintScreen"), (14, "Insert"),
    (29, "PageUp"), (44, "PageDown"), (58, "Home"), (72, "End"),
    (82, "ArrowRight"), (81, "ArrowDown"), (80, "ArrowLeft"),
    (79, "ControlRight"), (78, "Fn"), (77, "MetaRight"), (76, "Space"),
    (75, "MetaLeft"), (74, "AltLeft"), (73, "ControlLeft"),
    (59, "ShiftLeft"), (45, "CapsLock"), (30, "Tab"), (15, "Backquote"),
)
# Head first, followed by three progressively dimmer keys.
TRAILS = (
    ("#319DFF", "#2372BE", "#164B80", "#102C48"),
    ("#ED8055", "#B25C3C", "#783E29", "#47271B"),
)


MODE = dict(none="low", minimal="low", low="low", medium="medium", high="high",
            xhigh="peak", max="peak", ultra="peak")
INK = (TRAILS[0] + ("#A5E7FF",), TRAILS[1] + ("#FFD3A3",))
# Each entry is a color index, head first. Gaps let the second comet detach
# and catch up. Eleven beats divide evenly into a 33-key lap.
BEATS = (0, 0, 1, 1, 2, 2, 2, 1, 1, 0, 0)
PATTERNS = {
    "low": ((0, 2),),
    "medium": ((0, 1, 2, 3),),
    "high": ((4, 0, 1, 2, 2, 3, 3), (4, 0, 0, 1, 2, 3, 3), (4, 0, 1, 0, 1, 2, 3)),
    "peak": tuple((4, 0, 1, 2, 3) + (None,) * gap + (0, 1, 2, 3) for gap in (1, 2, 3)),
}


def key_frame(states, palette, phase, efforts=DEFAULT_EFFORTS):
    colors = [palette["idle"]] * 84
    size = len(PERIMETER)
    for product, state in enumerate(states):
        if state == "working":
            head = phase + product * (size // 2)
            patterns = PATTERNS[MODE.get(efforts[product], "medium")]
            pattern = patterns[BEATS[phase % len(BEATS)] % len(patterns)]
            for distance, ink in enumerate(pattern):
                if ink is not None:
                    index, _ = PERIMETER[(head - distance) % size]
                    colors[index] = INK[product][ink]
    # A stationary notice stays readable even as the other trail passes F1/F2.
    for indicator, state in enumerate(states, start=1):
        if state not in ("working", "idle"):
            colors[indicator] = palette[state]
    return colors


def studio_asset():
    data = dict(frameMs=round(FRAME_SECONDS * 1000), path=[code for _, code in PERIMETER],
                ink=INK, beats=BEATS, patterns=PATTERNS, modes=MODE)
    return "// Generated by python3 pixels.py\nconst perimeter = " + json.dumps(data, indent=2) + ";\n"


if __name__ == "__main__":
    Path(__file__).with_name("studio").joinpath("dist", "pixels.js").write_text(studio_asset())
