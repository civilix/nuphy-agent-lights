"""Air75 V3 ANSI pixel poses. Run this module to rebuild the offline Studio asset."""
import json
from pathlib import Path

FRAME_SECONDS = 0.5

# Each pixel pairs the bridge's RGB slot with the browser's KeyboardEvent.code.
# The slot order differs from the Studio DOM order after the function row.
CODEX = {
    "color": "#319DFF",
    "body": [(17, "Digit2"), (33, "KeyE"), (47, "KeyS")],
    "poses": [[(49, "KeyF")], []],
}
CLAUDE = {
    "color": "#ED8055",
    "body": [
        (21, "Digit6"), (22, "Digit7"), (23, "Digit8"), (24, "Digit9"), (25, "Digit0"), (26, "Minus"),
        (36, "KeyY"), (38, "KeyI"), (39, "KeyO"), (41, "BracketLeft"),
        (50, "KeyG"), (51, "KeyH"), (52, "KeyJ"), (53, "KeyK"), (54, "KeyL"), (55, "Semicolon"), (56, "Quote"),
    ],
    "poses": [
        [(64, "KeyB"), (65, "KeyN"), (68, "Period"), (69, "Slash")],
        [(63, "KeyV"), (65, "KeyN"), (67, "Comma"), (69, "Slash")],
    ],
}
SPRITES = (CODEX, CLAUDE)


def key_frame(states, palette, phase):
    colors = [palette["idle"]] * 84
    for indicator, (sprite, state) in enumerate(zip(SPRITES, states), start=1):
        colors[indicator] = palette[state]
        if state != "idle":
            pose = sprite["poses"][phase % len(sprite["poses"]) if state == "working" else 0]
            for index, _ in sprite["body"] + pose:
                colors[index] = sprite["color"]
    return colors


def studio_asset():
    # Classic script so double-clicking index.html also works offline.
    sprites = [dict(color=s["color"], body=[code for _, code in s["body"]],
                    poses=[[code for _, code in pose] for pose in s["poses"]]) for s in SPRITES]
    data = dict(frameMs=int(FRAME_SECONDS * 1000), sprites=sprites)
    return "// Generated by python3 pixels.py\nconst pixelArt = " + json.dumps(data, indent=2) + ";\n"


if __name__ == "__main__":
    Path(__file__).with_name("studio").joinpath("dist", "pixels.js").write_text(studio_asset())
